"""Check that the migrations produce exactly the schema the SQLAlchemy tables describe.

Creates a scratch database, upgrades it to head, fails on any autogenerate difference, then
downgrades to base and fails if anything but Alembic's version table remains. Uses
``HURON_TEST_DATABASE_URL`` when set, otherwise a ``postgres:16`` testcontainer.
"""

from __future__ import annotations

import asyncio
import sys
from pathlib import Path

import asyncpg
from alembic import command
from alembic.util.exc import AutogenerateDiffsDetected

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

from tests.support.postgres import alembic_config, migrated_database, server_url  # noqa: E402


def main() -> int:
    """Run the check; returns the process exit code."""
    try:
        with server_url() as server, migrated_database(server) as url:
            config = alembic_config(url)
            try:
                command.check(config)
            except AutogenerateDiffsDetected as error:
                print(f"schema map: migrations and tables disagree:\n{error}")
                return 1
            command.downgrade(config, "base")
            leftovers = asyncio.run(_leftovers(url))
            if leftovers:
                print(f"schema map: downgrade left objects behind: {leftovers}")
                return 1
    except Exception as error:  # noqa: BLE001 - report any infrastructure failure plainly
        print(f"schema map: could not run the check: {error}")
        return 2
    print("schema map: migrations match the tables; downgrade is clean")
    return 0


async def _leftovers(url: str) -> list[str]:
    connection = await asyncpg.connect(url)
    try:
        rows = await connection.fetch(
            "select 'table ' || table_name as name from information_schema.tables"
            " where table_schema = 'huron' and table_name <> 'alembic_version'"
            " union all select 'function ' || routine_name from information_schema.routines"
            " where routine_schema = 'huron'"
        )
    finally:
        await connection.close()
    return sorted(row["name"] for row in rows)


if __name__ == "__main__":
    raise SystemExit(main())
