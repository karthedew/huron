"""Generate the CLI reference of the docs site from the real ``huron`` command tree.

Writes one Markdown page per root command (with every visible subcommand), an overview page, an
index page per help panel and the sidebar of the reference, all under
``web/docs-site/src/content/docs/reference/cli/``. The panels and their order come from the CLI's
``LAYOUT``; hidden commands and options are left out. The pages are committed, so a review shows
every change to the CLI's help.

Usage: ``uv run python scripts/cli_reference.py`` regenerates the pages;
``uv run python scripts/cli_reference.py --check`` exits 1 when the committed pages differ.
"""

from __future__ import annotations

import argparse
import inspect
import json
import re
import sys
import unicodedata
from dataclasses import dataclass
from enum import Enum
from pathlib import Path
from typing import TYPE_CHECKING

import typer
from typer.core import TyperArgument, TyperGroup, TyperOption

from huron.applications.cli.app import app
from huron.applications.cli.commands import LAYOUT

if TYPE_CHECKING:
    from collections.abc import Callable, Iterator, Mapping, Sequence

    from typer._click import Command

ROOT = Path(__file__).resolve().parents[1]
OUTPUT = ROOT / "web" / "docs-site" / "src" / "content" / "docs" / "reference" / "cli"
BASE = "/docs/reference/cli"
SIDEBAR = "_sidebar.json"
PROGRAM = "huron"
REGENERATE = "uv run python scripts/cli_reference.py"
NOTE = (
    "<!-- Generated by scripts/cli_reference.py from the help of the huron CLI. "
    f"After you change the help, run `{REGENERATE}`. -->"
)


@dataclass(frozen=True)
class Param:
    """One argument or option of a command, as its reference shows it."""

    names: str
    kind: str
    default: str
    help: str


@dataclass(frozen=True)
class Node:
    """One visible command or command group, with its visible subcommands."""

    path: str
    help: str
    usage: str
    panel: str
    deprecated: bool
    arguments: tuple[Param, ...]
    options: tuple[Param, ...]
    children: tuple[Node, ...]

    @property
    def summary(self) -> str:
        """The first paragraph of the help on one line, as help listings show it."""
        return " ".join(self.help.split("\n\n", 1)[0].split())

    @property
    def anchor(self) -> str:
        """The heading anchor of this command on its page."""
        return slug(self.path)

    def walk(self) -> Iterator[Node]:
        """This node's descendants, depth first, in help order."""
        for child in self.children:
            yield child
            yield from child.walk()


def tree(application: typer.Typer = app, program: str = PROGRAM) -> Node:
    """The command tree of ``application`` (the ``huron`` CLI by default), as its help shows it."""
    root = typer.main.get_command(application)
    return _node(root, typer.Context(root, info_name=program), "")


def pages(root: Node, layout: Sequence[tuple[str, Sequence[str]]] = LAYOUT) -> dict[str, str]:
    """Every generated file, by its path under the output directory.

    Fails when a visible root command is missing from ``layout`` or a verb of ``layout`` does not
    exist, so the reference cannot drift from the help panels.
    """
    verbs = {child.path.split()[-1]: child for child in root.children}
    listed = [verb for _, panel_verbs in layout for verb in panel_verbs]
    unknown = sorted(set(listed) - set(verbs))
    unplaced = sorted(set(verbs) - set(listed))
    if unknown or unplaced:
        raise ValueError(f"LAYOUT names missing commands {unknown}, leaves out {unplaced}")
    files = {"index.md": _overview(root, verbs, layout)}
    sidebar: list[object] = [{"label": "Overview", "slug": _slug_of("")}]
    for panel, panel_verbs in layout:
        nodes = [verbs[verb] for verb in panel_verbs]
        panel_slug = slug(panel)
        files[f"panels/{panel_slug}.md"] = _panel_page(panel, nodes)
        for node in nodes:
            files[f"{_verb(node)}.md"] = _command_page(node, panel)
        items: list[object] = [{"label": "Overview", "slug": _slug_of(f"panels/{panel_slug}")}]
        items += [{"label": _verb(node), "slug": _slug_of(_verb(node))} for node in nodes]
        sidebar.append({"label": panel, "items": items})
    files[SIDEBAR] = json.dumps(sidebar, indent="\t") + "\n"
    return files


def differences(files: Mapping[str, str], output: Path) -> list[str]:
    """The paths under ``output`` that a write of ``files`` would add, change or remove."""
    existing = _existing(output)
    changed = [name for name, text in files.items() if existing.get(name) != text]
    removed = [name for name in existing if name not in files]
    return sorted(changed + removed)


def write(files: Mapping[str, str], output: Path) -> None:
    """Write ``files`` under ``output`` and remove every other file there."""
    for name in _existing(output):
        if name not in files:
            (output / name).unlink()
    for name, text in files.items():
        target = output / name
        target.parent.mkdir(parents=True, exist_ok=True)
        if not target.exists() or target.read_text() != text:
            target.write_text(text)


def slug(text: str) -> str:
    """The anchor GitHub and Astro give a heading of ``text`` (github-slugger, ASCII cases)."""
    lowered = text.strip().lower()
    return re.sub(r"[^\w\- ]", "", lowered).replace(" ", "-")


def main(argv: Sequence[str] | None = None) -> int:
    """Regenerate the reference, or with ``--check`` report whether it is current."""
    parser = argparse.ArgumentParser(description="Generate the CLI reference of the docs site.")
    parser.add_argument("--check", action="store_true", help="exit 1 when the pages are stale")
    parser.add_argument("--output", type=Path, default=OUTPUT, help="the output directory")
    args = parser.parse_args(argv)
    files = pages(tree())
    if args.check:
        stale = differences(files, args.output)
        for name in stale:
            print(f"stale: {args.output / name}", file=sys.stderr)
        if stale:
            print(f"hint: run `{REGENERATE}` and commit the result", file=sys.stderr)
        return 1 if stale else 0
    write(files, args.output)
    return 0


def _node(command: Command, ctx: typer.Context, panel: str) -> Node:
    children: list[Node] = []
    if isinstance(command, TyperGroup):
        for name in command.list_commands(ctx):
            child = command.commands[name]
            if child.hidden:
                continue
            child_ctx = typer.Context(child, info_name=name, parent=ctx)
            children.append(_node(child, child_ctx, _panel(child)))
    params = [param for param in command.params if not getattr(param, "hidden", False)]
    arguments = [param for param in params if isinstance(param, TyperArgument)]
    options = [param for param in params if isinstance(param, TyperOption)]
    return Node(
        path=ctx.command_path,
        help=_help(command.help),
        usage=_usage(ctx.command_path, arguments, bool(children)),
        panel=panel,
        deprecated=bool(command.deprecated),
        arguments=tuple(_argument(param) for param in arguments),
        options=tuple(_option(param) for param in options),
        children=tuple(_grouped(children)),
    )


def _panel(command: Command) -> str:
    panel = getattr(command, "rich_help_panel", None)
    return panel if isinstance(panel, str) else ""


def _grouped(children: list[Node]) -> list[Node]:
    """``children`` in help order: grouped by panel, panels in the order they first appear."""
    panels = list(dict.fromkeys(child.panel for child in children))
    return sorted(children, key=lambda child: panels.index(child.panel))


def _help(text: str | None) -> str:
    cleaned = inspect.cleandoc((text or "").split("\f", 1)[0])
    return "\n".join(line for line in cleaned.splitlines() if line.strip() != "\b").strip()


def _usage(path: str, arguments: list[TyperArgument], group: bool) -> str:
    pieces = [path, "[OPTIONS]"]
    for argument in arguments:
        name = (argument.name or "").upper()
        name += "..." if argument.nargs == -1 else ""
        pieces.append(name if argument.required else f"[{name}]")
    if group:
        pieces.append("COMMAND [ARGS]...")
    return " ".join(pieces)


def _argument(param: TyperArgument) -> Param:
    notes = ["Required."] if param.required else []
    if param.nargs == -1:
        notes.append("Takes any number of values.")
    return Param(
        (param.name or "").upper(),
        _kind(param.type),
        _default(param),
        _sentences(param.help, notes),
    )


def _option(param: TyperOption) -> Param:
    names = ", ".join(sorted(param.opts, key=lambda name: (not name.startswith("--"), name)))
    if param.secondary_opts:
        names += " / " + ", ".join(param.secondary_opts)
    notes: list[str] = []
    if param.required:
        notes.append("Required.")
    if param.multiple:
        notes.append("Repeatable.")
    if param.envvar:
        variables = [param.envvar] if isinstance(param.envvar, str) else list(param.envvar)
        notes.append("Environment: " + ", ".join(f"`{name}`" for name in variables) + ".")
    kind = "flag" if param.is_flag and not param.secondary_opts else _kind(param.type)
    return Param(names, kind, _default(param), _sentences(param.help, notes))


def _sentences(help_text: str | None, notes: list[str]) -> str:
    text = _help(help_text)
    if text and not text.endswith((".", "!", "?", ":", ";")):
        text += "."
    return " ".join([*filter(None, [text]), *notes])


def _kind(param_type: object) -> str:
    choices = getattr(param_type, "choices", None)
    if choices:
        return " \\| ".join(str(getattr(choice, "value", choice)) for choice in choices)
    return str(getattr(param_type, "name", "")) or "value"


def _default(param: TyperArgument | TyperOption) -> str:
    value = param.default
    flag = isinstance(param, TyperOption) and param.is_flag and not param.secondary_opts
    if value is None or callable(value) or (flag and value is False) or value in ((), [], ""):
        return ""
    if isinstance(value, Enum):
        value = value.value
    if isinstance(value, bool) and isinstance(param, TyperOption) and param.secondary_opts:
        # An on/off pair: name the flag that is in effect, as `--help` does (`no-resolved`).
        value = (param.opts if value else param.secondary_opts)[0].lstrip("-")
    elif isinstance(value, bool):
        value = "true" if value else "false"
    if isinstance(value, list | tuple):
        value = " ".join(str(item) for item in value)
    return f"`{value}`"


def _overview(
    root: Node, verbs: Mapping[str, Node], layout: Sequence[tuple[str, Sequence[str]]]
) -> str:
    lines = [*_frontmatter("CLI reference", root.summary), NOTE, "", _prose(root.help), ""]
    lines += ["## Usage", "", *_code(root.usage), ""]
    lines += [
        "Every command also takes `--help`, which prints the same reference in the terminal.",
        "",
    ]
    if root.options:
        lines += ["## Global options", "", *_options(root.options), ""]
    lines += ["## Commands", ""]
    for panel, panel_verbs in layout:
        lines += [f"### [{panel}]({_url(f'panels/{slug(panel)}')})", ""]
        lines += _commands([verbs[verb] for verb in panel_verbs], _command_link)
        lines.append("")
    return _join(lines)


def _panel_page(panel: str, nodes: list[Node]) -> str:
    summary = f"The commands of the {panel} panel of huron --help."
    lines = [*_frontmatter(f"{panel} commands", summary), NOTE, ""]
    lines += [f"The commands `huron --help` lists under **{panel}**.", ""]
    lines += [*_commands(nodes, _command_link), ""]
    return _join(lines)


def _command_page(node: Node, panel: str) -> str:
    lines = [*_frontmatter(node.path, node.summary, label=_verb(node)), NOTE, ""]
    if node.deprecated:
        lines += ["**Deprecated.**", ""]
    lines += [_prose(node.help), ""]
    lines += [f"Panel: [{panel}]({_url(f'panels/{slug(panel)}')}).", ""]
    lines += ["## Usage", "", *_code(node.usage), ""]
    lines += _params(node, "##")
    if node.children:
        lines += ["## Commands", "", *_subcommands(node), ""]
    for child in node.walk():
        lines += [f"## `{child.path}`", ""]
        if child.deprecated:
            lines += ["**Deprecated.**", ""]
        if child.help:
            lines += [_prose(child.help), ""]
        lines += [*_code(child.usage), ""]
        lines += _params(child, "###")
        if child.children:
            lines += ["### Commands", "", *_subcommands(child), ""]
    return _join(lines)


def _subcommands(node: Node) -> list[str]:
    panels = list(dict.fromkeys(child.panel for child in node.children))
    if panels == [""]:
        return _commands(list(node.children), _anchor_link)
    lines: list[str] = []
    for panel in panels:
        children = [child for child in node.children if child.panel == panel]
        lines += [f"**{panel or 'Commands'}**", "", *_commands(children, _anchor_link), ""]
    return lines[:-1]


def _params(node: Node, level: str) -> list[str]:
    lines: list[str] = []
    if node.arguments:
        rows = [[f"`{p.names}`", p.kind, _cell(p.help)] for p in node.arguments]
        lines += [f"{level} Arguments", "", *_table(["Argument", "Type", "Description"], rows), ""]
    if node.options:
        lines += [f"{level} Options", "", *_options(node.options), ""]
    return lines


def _options(options: tuple[Param, ...]) -> list[str]:
    rows = [[_option_names(p.names), p.kind, p.default, _cell(p.help)] for p in options]
    return _table(["Option", "Type", "Default", "Description"], rows)


def _option_names(names: str) -> str:
    return " / ".join(
        ", ".join(f"`{name}`" for name in side.split(", ")) for side in names.split(" / ")
    )


def _commands(nodes: list[Node], link: Callable[[Node], str]) -> list[str]:
    rows = [[link(node), _cell(node.summary)] for node in nodes]
    return _table(["Command", "Description"], rows)


def _command_link(node: Node) -> str:
    return f"[`{_verb(node)}`]({_url(_verb(node))})"


def _anchor_link(node: Node) -> str:
    return f"[`{node.path}`](#{node.anchor})"


def _verb(node: Node) -> str:
    return node.path.split()[1] if len(node.path.split()) > 1 else node.path


def _frontmatter(title: str, description: str, label: str = "") -> list[str]:
    lines = ["---", f"title: {_yaml(title)}", f"description: {_yaml(description)}"]
    if label:
        lines += ["sidebar:", f"  label: {_yaml(label)}"]
    return [*lines, "---", ""]


def _yaml(text: str) -> str:
    if re.fullmatch(r"[A-Za-z][A-Za-z0-9 .,()-]*", text) and not text.endswith(" "):
        return text
    if "'" in text and '"' not in text:
        return json.dumps(text, ensure_ascii=False)
    return "'" + text.replace("'", "''") + "'"


def _code(text: str) -> list[str]:
    return ["```text", text, "```"]


def _prose(text: str) -> str:
    return _escape(text)


def _cell(text: str) -> str:
    return _escape(" ".join(text.split())).replace("|", "\\|")


def _escape(text: str) -> str:
    """Help text as Markdown: code spans kept, characters Markdown or HTML would read escaped."""
    parts = re.split(r"(`+[^`]*?`+)", text)
    return "".join(
        _code_span(part) if index % 2 else _escape_plain(part) for index, part in enumerate(parts)
    )


def _code_span(span: str) -> str:
    """A code span with single backticks, as Markdown writes the RST-style ````name````."""
    return f"`{span.strip('`')}`"


def _escape_plain(text: str) -> str:
    return re.sub(r"([\\*<>\[\]_])", _escape_character, text)


def _escape_character(match: re.Match[str]) -> str:
    character = match.group(1)
    if character == "_":
        before = match.string[match.start() - 1 : match.start()]
        after = match.string[match.end() : match.end() + 1]
        return character if before.isalnum() and after.isalnum() else "\\_"
    if character in "<>":
        return "&lt;" if character == "<" else "&gt;"
    return "\\" + character


def _table(headers: list[str], rows: list[list[str]]) -> list[str]:
    """A Markdown table padded as Prettier pads it, so the web's format check accepts it."""
    widths = [
        max(3, *(_width(row[index]) for row in [headers, *rows])) for index in range(len(headers))
    ]

    def line(cells: list[str]) -> str:
        padded = [
            cell + " " * (width - _width(cell)) for cell, width in zip(cells, widths, strict=True)
        ]
        return "| " + " | ".join(padded) + " |"

    return [line(headers), line(["-" * width for width in widths]), *(line(row) for row in rows)]


def _width(text: str) -> int:
    return sum(
        0 if unicodedata.combining(c) else 2 if unicodedata.east_asian_width(c) in "WF" else 1
        for c in text
    )


def _url(path: str) -> str:
    return f"{BASE}/{path}/" if path else f"{BASE}/"


def _slug_of(path: str) -> str:
    return _url(path).removeprefix("/docs/").rstrip("/")


def _join(lines: list[str]) -> str:
    text = "\n".join(lines)
    return re.sub(r"\n{3,}", "\n\n", text).rstrip("\n") + "\n"


def _existing(output: Path) -> dict[str, str]:
    if not output.is_dir():
        return {}
    # Every file counts: the directory holds only generated pages, and Starlight would build (and
    # Pagefind index) any stray .md, .mdx or other content file left there.
    files = sorted(path for path in output.rglob("*") if path.is_file())
    return {path.relative_to(output).as_posix(): path.read_text(errors="replace") for path in files}


if __name__ == "__main__":
    raise SystemExit(main())
